CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL
        CHECK (role IN ('student', 'commandant'))
);

CREATE TABLE floor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    limit_w INTEGER NOT NULL CHECK (limit_w > 0),
    used_w INTEGER NOT NULL DEFAULT 0,
    timezone VARCHAR(100) NOT NULL DEFAULT 'Europe/Kyiv',

    CHECK (used_w >= 0 AND used_w <= limit_w)
);

CREATE TABLE machine (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    floor_id BIGINT NOT NULL REFERENCES floor(id),
    kind VARCHAR(20) NOT NULL
        CHECK (kind IN ('washer', 'dryer')),
    power_w INTEGER NOT NULL CHECK (power_w > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'available'
        CHECK (status IN (
            'available', 'reserved', 'running', 'out_of_service'
        ))
);

CREATE TABLE cycle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    machine_id BIGINT NOT NULL REFERENCES machine(id),
    program VARCHAR(100) NOT NULL,
    duration_min INTEGER NOT NULL CHECK (duration_min > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'held'
        CHECK (status IN (
            'held', 'running', 'done', 'expired', 'cancelled'
        )),
    version INTEGER NOT NULL DEFAULT 1 CHECK (version >= 1),
    price_kopecks INTEGER NOT NULL CHECK (price_kopecks > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,

    CHECK (expires_at > created_at),
    CHECK (finished_at IS NULL OR
           (started_at IS NOT NULL AND finished_at >= started_at))
);

COMMENT ON COLUMN cycle.price_kopecks IS
    'Вартість циклу в копійках (UAH)';

CREATE UNIQUE INDEX uq_machine_active_cycle
    ON cycle (machine_id)
    WHERE status IN ('held', 'running');